# -*- coding: utf-8 -*-
"""
一箭又一箭 —— 关卡数据

关卡用字符网格表示，写起来直观，改起来方便：
    '.'  空格子
    'U'  朝上的箭头
    'D'  朝下的箭头
    'L'  朝左的箭头
    'R'  朝右的箭头

【关卡是怎么设计出来的】
    这三个关卡由 level_gen.py 生成，不是手搓的。
    生成的硬条件有四条（每一条都是踩坑换来的）：
      1. 四个方向都必须出现，避免玩法单调；
      2. 开局能直接飞走的箭头不能太多，否则不用思考就能点掉一片；
      3. 同一行或同一列上，相邻位置连续同方向的箭头不能超过 2 个；
      4. 必须能被 solver.py 验证「确实可以通关」。

    第 3 条尤其重要 —— 早期版本为了让关卡「有顺序」，
    故意摆了一整排朝右的箭头当主链。结果玩起来就是从最右边开始
    一路往左点，纯机械劳动，试玩反馈「显得很呆」。
    现在限制连续同方向不能超过 2 个，箭头方向必须交错，一步一判断。

【难度怎么看】
    这个游戏里「移除箭头只会让路更通，不会新增阻挡」，
    所以玩家不可能把局面点死。难度其实来自两件事：
      - 箭头总数：越多，要观察的信息量越大；
      - 开局能飞的箭头数：越少，越难下手。
    因此不用「通关路径有多少条」来判断难易 —— 那个数字大不代表简单。
"""

from arrows import parse_level

# ---------------------------------------------------------------- 关卡定义
# 每关四个字段：
#   name    : 关卡名（界面显示）
#   mistakes: 允许的失误次数（点错一次扣 1，扣光就失败）。界面上用爱心表示。
#   seconds : 本关时间限制（秒）。倒计时到 0 还没清空，同样判定失败。
#
# 两个数值是怎么定的：
#
#   爱心统一给 2 颗 —— 只允许两次看走眼。
#   2 颗这个数是有讲究的：3 颗以上容错太足，玩家可以乱点碰运气；
#   只有 1 颗又太苛刻，一次手滑就重来容易劝退。2 颗刚好是
#   「允许你犯点小错，但不能一直瞎试」的平衡点。
#
#   时间给得很紧（10 / 15 / 20 秒） —— 这是有意设计的压力。
#   按正常思考节奏，10 秒其实只够扫视一遍棋盘再点几个，
#   所以必须先把「哪几个箭头前方是空的」看明白再动手，
#   而不是点一下想一下。棋盘上放的时间道具就是这根救命稻草：
#   顺路吃到一个，等于多了一半的思考时间。
#
#   三个关卡的时间跨度，和箭头数量基本成正比：
#     9 个箭头 / 10 秒　14 个箭头 / 15 秒　20 个箭头 / 20 秒

LEVEL_DEFS = [
    {
        "name": "第 1 关 · 牛刀小试",
        "mistakes": 2,
        "seconds": 10,
        # 6x6，9 个箭头，开局有 4 个可以直接飞走。
        # 箭头比较分散，主要用来熟悉「看方向、找空路」这个基本操作。
        "grid": [
            ". D . D L .",
            "R . U . . .",
            ". . R . . .",
            ". . . L L .",
            "U . . . . .",
            ". . . . . .",
        ],
    },
    {
        "name": "第 2 关 · 渐入佳境",
        "mistakes": 2,
        "seconds": 15,
        # 7x7，14 个箭头，开局有 4 个可以直接飞走。
        # 箭头开始聚集，上下左右互相牵制，需要掂量先后顺序。
        "grid": [
            ". . . . L . .",
            "R . . . U . .",
            "L . . . . . L",
            ". L R D . . .",
            ". . . R . . U",
            ". . U . . . .",
            ". . . . R U U",
        ],
    },
    {
        "name": "第 3 关 · 步步为营",
        "mistakes": 2,
        "seconds": 20,
        # 8x8，20 个箭头，开局有 5 个可以直接飞走。
        # 最大的一关：箭头密度最高，中部好几团互相卡住，
        # 基本每一步都要看清当前到底哪几个箭头还有出路。
        "grid": [
            ". . . . . . . .",
            ". U U L . . L L",
            ". . . D R . R R",
            ". U . . . L . .",
            ". L . L L . . .",
            ". . . . . . D L",
            ". . U . L . . .",
            "U . . . . . L .",
        ],
    },
]


# ---------------------------------------------------------------- 事件道具
#
# 【获取方式：必须被箭头「飞过」】
#   早期版本是「点一下就拿到」，太便宜了 —— 反正顺手一点，
#   等于白送时间。现在改成：只有当某个箭头沿着自己的方向
#   飞出棋盘、飞行路线正好扫过道具所在的格子时，才算拿到。
#   这样道具从「白送的按钮」变成了「路线规划的副产品」：
#   你得把箭头留给正确的时机，让它从道具上面穿过去。
#
# 【每关只放一个，且只给 +5 秒】
#   时间道具在这个游戏里价值最高（10 秒的关卡加 5 秒等于多一半），
#   放多了压力就没了。而且只有一个，玩家才会认真规划。
#
# 【位置是挑过的】
#   必须满足：道具在某个箭头的飞行路线上（否则永远吃不到），
#   但又不能开局就被顺手扫到（那就没意思了）。
#   三个关卡都是「先清掉挡路的箭头，再让后手从道具上飞过去」：
#
#     第 1 关 (1,3)：先点掉 (1,2)U，(1,0)R 的路才通，飞出时扫过 (1,3)
#     第 2 关 (3,6)：(2,0)L -> (2,6)L -> (4,6)U 这条链走完，才轮到它
#     第 3 关 (3,3)：先点掉 (4,1)L 和 (4,3)L，(2,3)D 才能一路向下扫过它
#
#   这条「一定拿得到」的性质由 test_core.py 里的用例守着 ——
#   万一以后调关卡把道具挪到了谁都扫不到的死角，测试会立刻报错。

EVENT_DEFS = {
    "第 1 关 · 牛刀小试": [
        {"r": 1, "c": 3, "kind": "time", "amount": 5},
    ],
    "第 2 关 · 渐入佳境": [
        {"r": 3, "c": 6, "kind": "time", "amount": 5},
    ],
    "第 3 关 · 步步为营": [
        {"r": 3, "c": 3, "kind": "time", "amount": 5},
    ],
}


class Level:
    """一个关卡：包含初始棋盘、允许的失误次数、时间限制和事件道具。"""

    def __init__(self, name, grid_lines, mistakes, seconds, events=None):
        self.name = name
        self.mistakes = mistakes
        self.seconds = seconds
        self.events = list(events or [])
        self.initial_board = parse_level(grid_lines)

    def fresh_events(self):
        """返回一份全新的事件列表（含 triggered 标记），重开时用。"""
        return [dict(e, triggered=False) for e in self.events]

    @property
    def rows(self):
        return self.initial_board.rows

    @property
    def cols(self):
        return self.initial_board.cols

    @property
    def arrow_count(self):
        return self.initial_board.count()

    def fresh_board(self):
        """返回一份全新的初始棋盘（重新开始或首次进入本关时用）。"""
        return self.initial_board.copy()


def build_levels():
    """构造全部关卡列表。"""
    return [
        Level(d["name"], d["grid"], d["mistakes"], d["seconds"],
              EVENT_DEFS.get(d["name"]))
        for d in LEVEL_DEFS
    ]


if __name__ == "__main__":
    # 直接运行本文件时，把三个关卡打印出来看看
    for lv in build_levels():
        print(f"=== {lv.name} ===")
        print(f"尺寸: {lv.rows} x {lv.cols}")
        print(f"箭头数: {lv.arrow_count}")
        print(f"允许失误: {lv.mistakes}")
        print(f"时间限制: {lv.seconds} 秒")
        print(f"事件道具: {len(lv.events)} 个")
        print(lv.initial_board)
        print()
